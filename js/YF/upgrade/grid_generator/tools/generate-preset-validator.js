import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';

const schemaUrl = new URL('../schemas/preset-1.2.schema.json', import.meta.url);
const outputUrl = new URL('../src/preset/generated/validatePreset12.js', import.meta.url);
const checkOnly = process.argv.includes('--check');

const schema = JSON.parse(await readFile(schemaUrl, 'utf8'));
const ajv = new Ajv2020({
    allErrors: true,
    strict: true,
    code: { esm: true, source: true }
});
const validate = ajv.compile(schema);
const banner = [
    '// Generated from schemas/preset-1.2.schema.json by tools/generate-preset-validator.js.',
    '// Do not edit this file manually.',
    ''
].join('\n');
const nextSource = `${banner}${standaloneCode(ajv, validate)}\n`;

if (checkOnly) {
    let currentSource = '';
    try {
        currentSource = await readFile(outputUrl, 'utf8');
    } catch {
        // The comparison below emits the actionable error.
    }
    if (currentSource !== nextSource) {
        console.error('Generated preset validator is stale. Run: npm --prefix tools run schema');
        process.exitCode = 1;
    } else {
        console.log('Preset validator matches the JSON Schema.');
    }
} else {
    await mkdir(new URL('./', outputUrl), { recursive: true });
    await writeFile(outputUrl, nextSource, 'utf8');
    console.log(`Generated ${fileURLToPath(outputUrl)}`);
}
