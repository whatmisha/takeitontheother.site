import { packagingNet } from '../src/packaging/PackagingModel.js';
import { tubeParameters } from '../src/packaging/TubeModel.js';

export async function checkTubes({ application, appDocument: doc, appWindow: win, assert, waitFor, presetFormat }) {
    const preview = application.packagingPreview, scene = preview.scene;
    const original = application.getStateSnapshot();
    preview.setFold(1);
    preview.setOpening(0);
    const change = (id, value) => {
        const input = doc.getElementById(id);
        input.value = String(value);
        input.dispatchEvent(new win.Event('change', { bubbles: true }));
    };
    change('constructionTypeSelect', 'tube');
    assert(scene.definition.type === 'tube' && scene.panels.length === 1, 'rigid tube replaces box planes with one curved wrap');
    assert(doc.getElementById('boxDimensionsControls').hidden && !doc.getElementById('tubeDimensionsControls').hidden, 'tube parameters replace rectangular box dimensions');
    assert(doc.querySelectorAll('#surfaceSettingsTabs > [data-surface-row]:not([hidden])').length === 1, 'single tube exposes only its editable body wrap');
    assert(scene.tubeAssembly.endPieces.length === 2 && doc.getElementById('previewOpenRow').hidden, 'single tube has two preview-only round ends');
    change('tubeDiameterInput', 120);
    change('tubeBodyHeightInput', 240);
    assert(Math.abs(application.settingsModule.get('frontWidth') - Math.PI * 120) < 1e-8 && application.settingsModule.get('frontHeight') === 240, 'diameter and height derive the exact rectangular wrap dimensions');
    const diameterBeforeInvalid = application.settingsModule.get('tubeDiameter');
    change('tubeDiameterInput', '');
    assert(application.settingsModule.get('tubeDiameter') === diameterBeforeInvalid, 'empty tube input restores its valid value');
    change('tubeDiameterInput', 0);
    assert(application.settingsModule.get('tubeDiameter') === 10, 'tube dimensions clamp to a positive supported range');
    application.undo();
    assert(application.settingsModule.get('tubeDiameter') === diameterBeforeInvalid, 'Undo restores a tube dimension together with its geometry');
    doc.getElementById('surfaceAddToggle').click();
    doc.querySelector('[data-add-surface="tubeCap"]').click();
    assert(scene.definition.type === 'telescopic-tube' && scene.panels.length === 2, 'Add Side creates a mating cap and its independent wrap');
    application.undo();
    assert(scene.panels.length === 1 && doc.querySelector('[data-net-add="tubeCap"]'), 'Undo removes only the new cap and restores its net handle');
    doc.querySelector('[data-net-add="tubeCap"]').dispatchEvent(new win.KeyboardEvent('keydown', { key: 'Enter', bubbles: true }));
    assert(scene.panels.length === 2 && !doc.querySelector('#surfaceSettingsTabs input:checked'), 'net handle adds a cap without automatically selecting it');
    change('tubeCapHeightInput', 80);
    change('tubeOverlapInput', 35);
    change('tubeWallInput', 1.5);
    change('tubeClearanceInput', 0.3);
    const p = tubeParameters(application.settingsModule.getAll());
    assert(Math.abs(p.capDiameter - 123.6) < 1e-8 && p.assembledHeight === 285, 'cap circumference accounts for wall thickness and fitting clearance');
    assert(doc.querySelector('[data-tube-overlap-guide] rect')?.getAttribute('height') > 0, 'net marks the body area covered by the closed cap');
    assert(doc.querySelectorAll('#surfaceSettingsTabs > [data-surface-row]:not([hidden])').length === 2 && !doc.querySelector('[data-surface-row="tubeCap"]').hidden, 'both lateral wraps are independent Sides rows');
    change('tubeOverlapInput', 999);
    assert(application.settingsModule.get('tubeOverlap') === 78.5, 'overlap stops before the round cap closure intersects the body');
    application.undo();
    assert(application.settingsModule.get('tubeOverlap') === 35, 'Undo restores the previous overlap');
    const body = scene.panels.find(panel => panel.spec.id === 'front');
    const bodyPosition = body.hinge.position.y;
    const cap = scene.panels.find(panel => panel.spec.id === 'tubeCap');
    const capPosition = cap.hinge.position.y;
    preview.setOpening(1);
    assert(body.hinge.position.y === bodyPosition && cap.hinge.position.y > capPosition + p.overlap, 'opening slides the cap clear of the body without moving the body');
    preview.setOpening(0);
    preview.setFold(0);
    assert(scene.panels.every(panel => Array.from(panel.exterior.geometry.attributes.position.array).filter((_, i) => i % 3 === 2).every(z => Math.abs(z) < 1e-7)), 'Unroll turns both cylindrical wraps into flat planes');
    assert(scene.tubeAssembly.endPieces.every(end => !end.visible), 'round ends stay out of the unrolled artwork');
    preview.setFold(1);
    assert(scene.tubeAssembly.endPieces.every(end => end.visible), 'Roll restores the round ends');
    doc.getElementById('surfaceSettingsTubeCap').click();
    assert(preview.selectedFace === 'tubeCap' && scene.selected === 'tubeCap', 'cap selection is synchronized between Sides and 3D');
    const graphic = application.objectNavigatorController.addGraphics({ name: 'Cap artwork test', svgContent: '<rect width="100" height="20" fill="#ffffff"/>', originalWidth: 100, originalHeight: 20 });
    assert(graphic.surface === 'tubeCap', 'new artwork is assigned to the selected cap wrap');
    doc.getElementById('surfaceOwnGridToggle').click();
    assert(application.surfaceManager.get('tubeCap').gridMode === 'own', 'cap supports its own independent grid');
    await waitFor(() => scene.texture && !preview.rendering && !doc.getElementById('previewStatus').textContent, 'tube artwork texture');
    assert(scene.panels.every(panel => panel.exterior.material.map === scene.texture), 'body and cap sample their own rectangles in the same artwork atlas');
    const net = packagingNet(application.settingsModule.getAll());
    const exported = await application.exportDocumentBuilder.build(false);
    assert(Math.abs(parseFloat(exported.getAttribute('width')) - net.width) < 1e-8 && Math.abs(parseFloat(exported.getAttribute('height')) - net.height) < 1e-8, 'SVG artboard encloses both tube wraps at exact millimeter sizes');
    assert(exported.querySelector('#surface-export-tubeCap') && !exported.querySelector('[data-surface-overlay], [data-tube-overlap-guide], #box circle'), 'cap artwork is exported while preview-only ends and handles are excluded');
    const source = { settings: application.settingsModule.getAll(), textBlocks: application.objectDocument.textBlocks, graphicsBlocks: application.objectDocument.graphicsBlocks };
    const restored = presetFormat.normalize(JSON.parse(JSON.stringify(presetFormat.organize(source))));
    assert(restored.settings.tubeOverlap === 35 && restored.settings.tubeClearance === 0.3 && restored.graphicsBlocks.some(block => block.id === graphic.id && block.surface === 'tubeCap'), 'JSON round trip preserves tube dimensions and cap artwork');
    await application.draftRecoveryController.saveNow();
    const draft = await application.draftRecoveryController.store.load();
    assert(draft.snapshot.settings.constructionType === 'telescopic-tube' && draft.snapshot.settings.tubeDiameter === 120, 'autosave includes tube construction and physical parameters');
    doc.querySelector('[data-surface-visibility="tubeCap"]').click();
    assert(scene.panels.length === 1 && doc.querySelector('[data-net-add="tubeCap"]'), 'hiding the cap removes its whole 3D part and offers restoration');
    doc.querySelector('[data-net-add="tubeCap"]').dispatchEvent(new win.KeyboardEvent('keydown', { key: 'Enter', bubbles: true }));
    assert(scene.panels.length === 2 && application.objectDocument.getGraphicsBlock(graphic.id), 'restoring the cap keeps its artwork');
    scene.camera.position.set(0, 1000, 0.01);
    scene.controls.target.set(0, 0, 0);
    scene.controls.update();
    scene.model.updateMatrixWorld(true);
    const bounds = scene.renderer.domElement.getBoundingClientRect();
    scene.pointerStart = [bounds.x + bounds.width / 2, bounds.y + bounds.height / 2];
    scene.pick({ button: 0, clientX: scene.pointerStart[0], clientY: scene.pointerStart[1] });
    assert(preview.selectedFace === null, 'clicking an uneditable round end does not select a hidden wrap behind it');
    change('constructionTypeSelect', original.settings.constructionType);
    assert(application.settingsModule.get('frontWidth') === original.settings.frontWidth && application.settingsModule.get('frontHeight') === original.settings.frontHeight, 'returning to a box restores its previous dimensions');
    assert(scene.panels.every(panel => panel.spec.shape !== 'cylinder') && !scene.tubeAssembly, 'box preview restores its hinge tree after leaving tube mode');
    change('constructionTypeSelect', 'telescopic-tube');
    assert(application.settingsModule.get('tubeDiameter') === 120 && application.objectDocument.getGraphicsBlock(graphic.id), 'returning to the tube preserves its parameters and cap artwork');
    scene.setView('iso');
}
