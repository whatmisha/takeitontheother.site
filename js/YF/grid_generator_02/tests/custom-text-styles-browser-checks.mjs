export async function checkCustomTextStyles({ application: app, appDocument: doc, appWindow: win, assert, waitFor, presetFormat }) {
    await app.packagingPreview.setMode('2d');
    const source = app.getStateSnapshot();
    const settings = app.settingsModule;
    const custom = () => settings.get('customTextStyles');
    const select = (node, value) => { node.value = String(value); node.dispatchEvent(new win.Event('change', { bubbles: true })); };
    const enter = (node, value) => { node.focus(); node.value = String(value); node.dispatchEvent(new win.Event('input', { bubbles: true })); node.blur(); };
    const section = id => doc.querySelector(`[data-custom-style="${id}"]`);
    const field = (id, key) => section(id).querySelector(`[data-field="${key}"]`);
    select(doc.getElementById('newStyleSource'), 'text');
    doc.getElementById('addTextStyle').click();
    const id = custom()[0].id;
    assert(custom().length === 1 && custom()[0].size === settings.get('textSize'), 'Add style copies the chosen brand style into an independent definition');
    enter(field(id, 'name'), 'Инструкция');
    assert(field(id, 'title').textContent === 'Инструкция' && [...doc.getElementById('paragraphStyleSelect').options].some(o => o.value === id && o.text === 'Инструкция'), 'renaming a style updates its panel and the paragraph style picker');
    field(id, 'size-mod').click();
    enter(field(id, 'size'), 0.825);
    enter(field(id, 'lineHeight'), 1.5);
    enter(field(id, 'tracking'), 0.02);
    select(field(id, 'fontWeight'), 400);
    assert(custom()[0].size === 0.825 && settings.get('textSize') !== 0.825 && custom()[0].tracking === 0.02, 'editing a custom style does not change the brand style');
    const block = app.objectNavigatorController.addText({ content: 'Инструкция по использованию\nВторой абзац', surface: 'front', width: 4 });
    app.objectEditorPanelController.openTextPanel(block.id);
    select(doc.getElementById('paragraphStyleSelect'), id);
    assert(app.objectDocument.getTextBlock(block.id).styleRef === id, 'a custom style is applied through the paragraph editor');
    const rendered = doc.querySelector(`#text-group-${block.id} text`);
    assert(rendered.getAttribute('font-weight') === '400' && rendered.getAttribute('letter-spacing') === '0.02em', '2D text renders the custom weight and tracking');
    const beforeUnit = JSON.stringify(custom());
    field(id, 'size-pt').click();
    assert(JSON.stringify(custom()) === beforeUnit && Math.abs(Number(field(id, 'size').value) - app.textStyleResolver.calculateFontSize(id) * 2.83465) < 0.001, 'changing units preserves the exact style definition');
    enter(field(id, 'size'), 18);
    assert(Math.abs(app.textStyleResolver.calculateFontSize(id) * 2.83465 - 18) < 1e-8, 'point sizes convert correctly to the grid-based style');
    app.undo();
    assert(JSON.stringify(custom()) === beforeUnit, 'one Undo restores the value before typing a point size');
    app.redo();
    assert(Math.abs(app.textStyleResolver.calculateFontSize(id) * 2.83465 - 18) < 1e-8, 'Redo restores a point size without rounding drift');
    field(id, 'size-mod').click();
    const precise = JSON.stringify(custom()), historyIndex = app.historyManager.historyIndex;
    field(id, 'size').focus(); field(id, 'size').blur();
    assert(JSON.stringify(custom()) === precise && app.historyManager.historyIndex === historyIndex, 'focusing and leaving a rounded numeric field preserves exact values and history');
    const trackingBefore = custom()[0].tracking;
    field(id, 'tracking').focus();
    field(id, 'tracking').dispatchEvent(new win.KeyboardEvent('keydown', { key: 'ArrowUp', bubbles: true }));
    field(id, 'tracking').dispatchEvent(new win.KeyboardEvent('keydown', { key: 'ArrowUp', bubbles: true }));
    field(id, 'tracking').blur();
    assert(Math.abs(custom()[0].tracking - trackingBefore - 0.002) < 1e-9, 'custom numeric fields support repeated keyboard adjustment');
    app.undo();
    assert(custom()[0].tracking === trackingBefore, 'keyboard adjustments within one edit form one Undo action');
    field(id, 'duplicate').click();
    const copyId = custom()[1].id;
    assert(copyId !== id && custom()[1].name === 'Инструкция copy' && custom()[1].size === custom()[0].size, 'Duplicate creates an independent style with a unique ID');
    field(copyId, 'name').blur();
    field(id, 'delete').click();
    assert(!field(id, 'deleteOptions').hidden && custom().length === 2, 'deleting a used style exposes an explicit replacement choice');
    select(field(id, 'replacement'), copyId);
    field(id, 'confirmDelete').click();
    assert(!section(id) && app.objectDocument.getTextBlock(block.id).styleRef === copyId, 'deleting a style reassigns all references in the same action');
    app.undo();
    assert(section(id) && app.objectDocument.getTextBlock(block.id).styleRef === id, 'Undo restores the deleted definition and its paragraph references together');
    app.redo();
    assert(!section(id) && custom().length === 1 && app.objectDocument.getTextBlock(block.id).styleRef === copyId, 'Redo removes the style without dangling references');
    select(field(copyId, 'fontFamily'), 'Lunnen Display');
    select(field(copyId, 'fontWeight'), 300);
    assert(custom()[0].fontFamily === 'Lunnen Display' && doc.querySelector(`#text-group-${block.id} text`).getAttribute('font-variation-settings') === "'wght' 300", 'custom Lunnen Display uses the chosen variable weight');
    const saved = { settings: settings.getAll(), textBlocks: app.objectDocument.textBlocks, graphicsBlocks: app.objectDocument.graphicsBlocks };
    const organized = presetFormat.organize(saved);
    const roundtrip = presetFormat.normalize(organized);
    assert(roundtrip.settings.customTextStyles[0].id === copyId && roundtrip.textBlocks.find(b => b.id === block.id).styleRef === copyId, 'JSON retains custom styles and their stable references');
    const svg = await app.exportDocumentBuilder.build(false);
    assert(svg.querySelector(`#text-group-${block.id} text`)?.getAttribute('font-family').startsWith('Lunnen Display'), 'SVG/PDF source keeps the custom font family');
    const previousTexture = app.packagingPreview.scene.texture;
    await app.packagingPreview.setMode('3d');
    await waitFor(() => app.packagingPreview.scene.texture !== previousTexture && !app.packagingPreview.rendering, 'custom style in 3D');
    assert(app.packagingPreview.scene.texture.image.width > 0, '3D renders artwork containing custom typography');
    await app.draftRecoveryController.saveNow();
    const draft = await app.draftRecoveryController.store.load();
    assert(draft.snapshot.settings.customTextStyles[0].name === 'Инструкция copy', 'autosave retains the custom style definition');
    const url = await app.presetShareController.buildUrl();
    const iframe = document.createElement('iframe');
    const shared = new URL(url); shared.searchParams.set('browser-smoke', 'custom-styles-open');
    iframe.src = shared.href; document.body.appendChild(iframe);
    let opened;
    try {
        await waitFor(() => {
            opened = iframe.contentWindow?.[Symbol.for('lunnen.grid-generator-02.application')];
            return opened?.currentPresetName?.startsWith('Shared —');
        }, 'custom styles from a fresh shared link');
        assert(opened.settingsModule.get('customTextStyles')[0].name === 'Инструкция copy' && opened.objectDocument.getTextBlock(block.id).styleRef === copyId, 'a fresh shared link restores the custom style and paragraph assignment');
        assert(iframe.contentDocument.querySelector(`[data-custom-style="${copyId}"]`), 'shared custom styles appear as editable typography sections');
        opened.presetApplicationController.applyDocumentState(source, { closeEditors: true });
        assert(opened.settingsModule.get('customTextStyles').length === 0 && !iframe.contentDocument.querySelector('[data-custom-style]'), 'switching to a document without custom styles clears the old list');
    } finally { if (opened) { opened.hasUnsavedChanges = false; opened.dispose(); } iframe.remove(); }
    app.presetApplicationController.applyDocumentState(source, { closeEditors: true });
}
