export async function checkMarkings({ application: app, appDocument: doc, appWindow: win, assert, waitFor, presetFormat }) {
    await app.packagingPreview.setMode('2d');
    const panel = doc.getElementById('markingsPanel');
    const fields = Object.fromEntries([...panel.querySelectorAll('[data-marking-field]')].map(node => [node.dataset.markingField, node]));
    const change = (node, value) => { node.value = String(value); node.dispatchEvent(new win.Event('change', { bubbles: true })); };
    const enter = (id, value) => { const node = doc.getElementById(id); node.focus(); node.value = String(value); node.blur(); };
    const visibleIds = container => [...container.querySelectorAll('[data-marking-id]')].map(node => node.dataset.markingId);
    const enabled = id => fields.list.querySelector(`[data-marking-row="${id}"] input`);
    const closeTo = (a,b) => Math.abs(a-b) < 1e-6;
    const source = app.getStateSnapshot();
    doc.getElementById('surfaceSettingsTubeCap').click();
    if (app.surfaceManager.isVisible('tubeCap')) doc.querySelector('[data-surface-visibility="tubeCap"]').click();
    const before = JSON.stringify(app.getStateSnapshot());
    const count = app.objectDocument.graphicsBlocks.length;
    doc.getElementById('addMarkingsBtn').click();
    assert(panel.style.display === 'flex' && fields.list.children.length === 7, 'Objects opens the seven-sign marking catalog');
    change(fields.set, 'individual');
    assert(fields.apply.disabled && !visibleIds(fields.preview).length, 'individual selection starts empty without toggling off a whole set');
    enabled('eac-v1').click();
    assert(!fields.apply.disabled && visibleIds(fields.preview).join(',') === 'eac-v1', 'a single catalog sign can be added as its own object');
    change(fields.set, 'handling');
    enabled('eac-v1').click();
    fields.list.querySelector('button[aria-label="Move EAC up"]').click();
    change(fields.direction, 'column'); change(fields.align, 'end');
    enter('markingHeightValue', 1.25); enter('markingGapValue', 0.5);
    assert(JSON.stringify(app.getStateSnapshot()) === before, 'catalog preview edits leave the document and hidden surface unchanged until Apply');
    assert(visibleIds(fields.preview).join(',') === 'fragile-v1,eac-v1,keep-dry-v1' && !fields.alignGroup.hidden, 'preview follows sign selection, order and vertical layout');
    fields.cancel.click();
    assert(JSON.stringify(app.getStateSnapshot()) === before && panel.style.display === 'none', 'Cancel discards the catalog draft without a history action');
    doc.getElementById('addMarkingsBtn').click();
    change(fields.set, 'handling'); change(fields.direction, 'column'); change(fields.align, 'end');
    enter('markingHeightValue', 1.25); enter('markingGapValue', 0.5);
    fields.apply.click();
    let block = app.objectDocument.graphicsBlocks.find(item => item.markings);
    const id = block.id;
    assert(block.surface === 'tubeCap' && app.surfaceManager.isVisible('tubeCap') && app.objectDocument.graphicsBlocks.length === count+1, 'adding markings targets the selected cap and restores it in the same action');
    assert(closeTo(block.heightInModules, 3.125) && block.markings.gap === 0.5, 'vertical group size retains the requested individual icon height and interval');
    assert(visibleIds(doc.getElementById(`graphics-group-${id}`)).join(',') === 'fragile-v1,keep-dry-v1', '2D renders the enabled signs as vectors');
    assert(!doc.getElementById('editMarkingsBtn').hidden && doc.getElementById('fileUploadArea').style.display === 'none', 'the graphics editor exposes Edit markings for a catalog group');
    doc.getElementById('addGraphicsBtn').click();
    assert(app.currentEditingGraphicsId === null && doc.getElementById('fileUploadArea').style.display === 'block' && doc.getElementById('editMarkingsBtn').hidden, 'Add Graphics after a catalog group starts a fresh upload instead of replacing the group');
    app.undo();
    assert(!app.objectDocument.getGraphicsBlock(id) && !app.surfaceManager.isVisible('tubeCap'), 'one Undo removes the marking group and restores hidden-side state');
    app.redo(); block = app.objectDocument.getGraphicsBlock(id);
    assert(block.markings.direction === 'column' && app.surfaceManager.isVisible('tubeCap'), 'Redo restores the editable marking recipe and target side');
    app.objectEditorPanelController.openGraphicsPanel(id); doc.getElementById('editMarkingsBtn').click();
    assert(closeTo(Number(doc.getElementById('markingHeightValue').value), 1.25), 'reopening the catalog derives the same individual icon height');
    enabled('fragile-v1').click(); enabled('keep-dry-v1').click();
    assert(fields.apply.disabled && !visibleIds(fields.preview).length, 'an empty selection cannot be applied');
    enabled('pap20-v1').click(); enabled('weee-v1').click();
    change(fields.direction, 'row'); enter('markingGapValue', 0.75);
    fields.apply.click(); block = app.objectDocument.getGraphicsBlock(id);
    const edited = JSON.stringify(block.markings);
    assert(visibleIds(doc.getElementById(`graphics-group-${id}`)).join(',') === 'pap20-v1,weee-v1' && closeTo(block.heightInModules, 1.25), 'editing changes the set and layout while retaining icon height and object identity');
    app.undo(); assert(app.objectDocument.getGraphicsBlock(id).markings.direction === 'column', 'Undo restores the previous marking set');
    app.redo(); block = app.objectDocument.getGraphicsBlock(id);
    assert(JSON.stringify(block.markings) === edited, 'Redo restores membership, order and spacing');
    const copy = app.objectNavigatorController.duplicate('graphics', id, true);
    copy.markings.items[0].enabled = !copy.markings.items[0].enabled;
    assert(JSON.stringify(block.markings) === edited, 'duplicated marking recipes do not share mutable item arrays');
    app.undo();
    const exportSvg = await app.exportDocumentBuilder.build(false);
    assert(exportSvg.querySelector('[data-marking-id="pap20-v1"] path') && !exportSvg.querySelector('[data-marking-field]'), 'SVG/PDF artwork contains vector signs and no catalog controls');
    const roundTrip = presetFormat.normalize(presetFormat.organize({ settings: app.settingsModule.getAll(), textBlocks: app.objectDocument.textBlocks, graphicsBlocks: app.objectDocument.graphicsBlocks }));
    assert(JSON.stringify(roundTrip.graphicsBlocks.find(item => item.id === id).markings) === edited, 'JSON preserves disabled membership, order and grouping parameters');
    const oldTexture = app.packagingPreview.scene.texture;
    await app.packagingPreview.setMode('3d');
    await waitFor(() => app.packagingPreview.scene.texture !== oldTexture && !app.packagingPreview.rendering, 'markings in the 3D cap texture');
    assert(app.packagingPreview.scene.texture.image.width > 0, '3D rebuilds the texture with catalog markings');
    await app.draftRecoveryController.saveNow();
    const draft = await app.draftRecoveryController.store.load();
    assert(draft.snapshot.document.graphicsBlocks.some(item => item.id === id && JSON.stringify(item.markings) === edited), 'autosave retains the editable marking group');
    const url = await app.presetShareController.buildUrl();
    const codec = await app.presetShareController.getCodec();
    const prepared = codec.prepare({ settings: app.settingsModule.getAll(), textBlocks: app.objectDocument.textBlocks, graphicsBlocks: app.objectDocument.graphicsBlocks });
    assert(prepared.document.graphics.blocks.find(item => item.id === id).svg === '', 'share links carry the recipe instead of SVG paths for catalog groups');
    const iframe = document.createElement('iframe'); const shared = new URL(url);
    shared.searchParams.set('browser-smoke', 'markings-share'); iframe.src = shared.href; document.body.appendChild(iframe);
    let opened;
    try {
        await waitFor(() => { opened = iframe.contentWindow?.[Symbol.for('lunnen.grid-generator-02.application')]; return opened?.currentPresetName?.startsWith('Shared —'); }, 'marking group from a fresh shared link');
        const restored = opened.objectDocument.getGraphicsBlock(id);
        assert(restored && !restored.missingAsset && JSON.stringify(restored.markings) === edited && restored.svgContent.includes('pap20-v1'), 'a fresh link reconstructs editable vector markings without relinking');
        opened.objectEditorPanelController.openGraphicsPanel(id);
        iframe.contentDocument.getElementById('editMarkingsBtn').click();
        assert(iframe.contentDocument.getElementById('markingsPanel').style.display === 'flex', 'the shared marking group can be edited through the catalog again');
    } finally { if (opened) { opened.hasUnsavedChanges = false; opened.dispose(); } iframe.remove(); }
    // Explicit conversion of a legacy slot is reversible; simply opening it keeps the old artwork.
    await app.packagingPreview.setMode('2d');
    const asset = await app.graphicsAssetController.load('graphics/icons.svg');
    let legacy = app.objectDocument.getGraphicsBlock('icons');
    if (!legacy) legacy = app.objectNavigatorController.addGraphics({ id: 'icons', isBuiltIn: true, name: 'Icons', svgContent: asset.content, originalWidth: asset.width, originalHeight: asset.height });
    const legacySvg = legacy.svgContent;
    app.objectEditorPanelController.openGraphicsPanel('icons'); doc.getElementById('editMarkingsBtn').click();
    fields.cancel.click();
    assert(app.objectDocument.getGraphicsBlock('icons').svgContent === legacySvg && !app.objectDocument.getGraphicsBlock('icons').markings, 'opening and cancelling the legacy catalog leaves the original icons untouched');
    app.objectEditorPanelController.openGraphicsPanel('icons'); doc.getElementById('editMarkingsBtn').click();
    change(fields.set, 'keyboard'); fields.apply.click();
    assert(app.objectDocument.getGraphicsBlock('icons').markings && doc.getElementById('editMarkingsBtn').textContent === 'Edit markings', 'Choose markings explicitly turns the legacy slot into an editable catalog group');
    app.undo();
    assert(app.objectDocument.getGraphicsBlock('icons').svgContent === legacySvg && !app.objectDocument.getGraphicsBlock('icons').markings, 'Undo restores the exact legacy SVG');
    app.presetApplicationController.applyDocumentState(source, { closeEditors: true });
}
