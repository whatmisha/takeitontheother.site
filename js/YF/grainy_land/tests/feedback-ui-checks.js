 const before=d.querySelector('#mainCanvas').getContext('2d').getTransform(),rect=canvas.getBoundingClientRect();
 const point={bubbles:true,cancelable:true,button:0,buttons:1,clientX:rect.left+400,clientY:rect.top+250};
