 const tap=async(target=canvas,extra={})=>{key('keydown',target,extra);key('keyup',target,extra);await pause();};
 await tap();check('Space starts animation',playing()&&play.textContent==='Stop');
 await tap();check('Space stops animation',!playing()&&play.textContent==='Play');
 play.click();await tap();check('Space stops animation started by Play',!playing());
 key('keydown');for(let i=0;i<4;i++)key('keydown',canvas,{repeat:true});key('keyup');await pause();
 check('Holding Space toggles only once',playing());await tap();
 await tap(play);check('Space works with Play focused',playing());await tap(play);
 for(const modifier of ['metaKey','ctrlKey','altKey','shiftKey'])await tap(canvas,{[modifier]:true});
 check('Modified Space does not start animation',!playing());
 await tap(d.querySelector('#motionAmount'));check('Space in an input does not start animation',!playing());
 await tap(d.querySelector('#generateBtn'));check('Space on another button does not start animation',!playing());
 const dialog=d.createElement('dialog');d.body.append(dialog);dialog.showModal();await tap(canvas);dialog.close();dialog.remove();
