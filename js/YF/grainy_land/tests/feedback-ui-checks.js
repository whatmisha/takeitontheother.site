 canvas.dispatchEvent(new w.MouseEvent('mousedown',point));d.dispatchEvent(new w.MouseEvent('mousemove',{...point,clientX:point.clientX+24,clientY:point.clientY+16}));
 d.dispatchEvent(new w.MouseEvent('mouseup',{...point,buttons:0}));canvas.dispatchEvent(new w.PointerEvent('pointerup',{...point,pointerId:1,buttons:0}));key('keyup');await pause();
 const after=d.querySelector('#mainCanvas').getContext('2d').getTransform();
 check('Space + drag pans without starting animation',!playing()&&after.e!==before.e&&after.f!==before.f);
 const pinRow=d.querySelector('#layerList > [data-layer-id]').dataset.layerId;
 const pin=()=>d.querySelector('[data-layer-id="'+pinRow+'"] [data-action="pin"]');
 const filled=()=>w.getComputedStyle(pin().querySelector('svg')).fill===w.getComputedStyle(pin().querySelector('svg')).color;
 check('Unpinned icon is an outline',pin().getAttribute('aria-pressed')==='false'&&!filled());
 pin().click();await pause();check('Pinned icon is filled like Wander Wall',pin().getAttribute('aria-pressed')==='true'&&filled());
 d.dispatchEvent(new w.KeyboardEvent('keydown',{key:'z',code:'KeyZ',metaKey:true,bubbles:true,cancelable:true}));await pause();
 check('Undo restores outline pin',pin().getAttribute('aria-pressed')==='false'&&!filled());
 pin().click();await pause();pin().click();await pause();check('Unpin removes fill',!filled());
 check('Flora label',d.querySelector('label[for="modeFlower"]').textContent==='Flora');
 const rows=[...d.querySelectorAll('#layerList > [data-layer-id]')];hover(rows[0]);
