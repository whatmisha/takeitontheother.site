import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';

// Both contracts are compiled: 2.0 is what the app reads and writes, 1.2 is
// still validated before migration so a corrupt legacy file fails loudly.
const contracts = [
    { schema: 'preset-1.2.schema.json', output: 'validatePreset12.js' },
    { schema: 'preset-2.0.schema.json', output: 'validatePreset20.js' }
];
const checkOnly = process.argv.includes('--check');

async function build({ schema: schemaName, output }) {
    const schemaUrl = new URL(`../schemas/${schemaName}`, import.meta.url);
    const outputUrl = new URL(`../src/preset/generated/${output}`, import.meta.url);
    const schema = JSON.parse(await readFile(schemaUrl, 'utf8'));
    const ajv = new Ajv2020({
        allErrors: true,
        strict: true,
        code: { esm: true, source: true }
    });
    const validate = ajv.compile(schema);
    const banner = [
        `// Generated from schemas/${schemaName} by tools/generate-preset-validator.js.`,
        '// Do not edit this file manually.',
        ''
    ].join('\n');
    const nextSource = `${banner}${standaloneCode(ajv, validate)}\n`;

    if (checkOnly) {
        let currentSource = '';
        try {
            currentSource = await readFile(outputUrl, 'utf8');
        } catch {
            // The comparison below emits the actionable error.
        }
        if (currentSource !== nextSource) {
            console.error(`Generated ${output} is stale. Run: npm --prefix tools run schema`);
            return false;
        }
        console.log(`${output} matches ${schemaName}.`);
        return true;
    }

    await mkdir(new URL('./', outputUrl), { recursive: true });
    await writeFile(outputUrl, nextSource, 'utf8');
    console.log(`Generated ${fileURLToPath(outputUrl)}`);
    return true;
}

const results = [];
for (const contract of contracts) {
    results.push(await build(contract));
}
if (results.includes(false)) process.exitCode = 1;
